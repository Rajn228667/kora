/// KORA localization — RU / KK / EN.
///
/// Every user-facing string goes through [S.t]. The active language
/// lives in [S.lang], kept in sync by `languageProvider`
/// (core/settings/settings_provider.dart) — widgets rebuild via
/// `ref.watch(languageProvider)`.
library;

enum AppLanguage { ru, kk, en }

abstract final class S {
  static AppLanguage lang = AppLanguage.ru;

  static String t(String key, [Map<String, String>? params]) {
    final table = switch (lang) {
      AppLanguage.kk => _kk,
      AppLanguage.en => _en,
      AppLanguage.ru => _ru,
    };
    var value = table[key] ?? _ru[key] ?? key;
    params?.forEach((k, v) => value = value.replaceAll('{$k}', v));
    return value;
  }

  /// All keys of a language table (used by tests for coverage checks).
  static Set<String> keys(AppLanguage l) => switch (l) {
        AppLanguage.kk => _kk.keys.toSet(),
        AppLanguage.en => _en.keys.toSet(),
        AppLanguage.ru => _ru.keys.toSet(),
      };

  /// camelCase enum name → snake_case key suffix.
  static String snake(String name) => name.replaceAllMapped(
        RegExp(r'[A-Z]'),
        (m) => '_${m.group(0)!.toLowerCase()}',
      );

