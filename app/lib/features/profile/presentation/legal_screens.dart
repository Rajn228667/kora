1. ОБЩЕЕ
KORA — платформа, соединяющая покупателей, магазины/рестораны и курьеров в Казахстане. Оформляя заказ, вы заключаете договор купли-продажи с соответствующим магазином; KORA обеспечивает витрину, оплату и логистику.

2. ЗАКАЗЫ
Состав, цена и наличие проверяются при оформлении. Если цена или остаток изменились — заказ не создаётся, вы увидите актуальные данные. Заказ считается принятым после подтверждения оплаты платёжной системой.

3. ОПЛАТА
Оплата выполняется через платёжного провайдера (Kaspi). Подтверждением оплаты является ответ провайдера на сервер KORA.

4. ДОСТАВКА
Точка доставки фиксируется при оформлении заказа. Курьер доставляет заказ по указанной точке и контактирует через чат или звонок внутри приложения.

5. ОТМЕНА И ВОЗВРАТ
Заказ можно отменить до начала приготовления. При отмене оплата возвращается на исходный способ. Споры по качеству решаются через службу поддержки.

6. РОЛИ
Менеджеры магазинов отвечают за актуальность меню и цен. Курьеры обязуются доставлять заказы в разумные сроки. Администрация вправе блокировать аккаунты за нарушения — все действия фиксируются в журнале аудита.

7. ПРЕКРАЩЕНИЕ
Вы можете удалить аккаунт в приложении. Мы можем ограничить доступ при мошенничестве или злоупотреблении сервисом.
''';
