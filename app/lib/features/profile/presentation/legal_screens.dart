import 'package:flutter/material.dart';
import '../../../core/l10n/app_strings.dart';
import '../../../core/theme/app_metrics.dart';
import '../../../core/theme/app_typography.dart';

/// Legal documents ship inside the app so they render offline and
/// match the actual data practices.
class LegalScreen extends StatelessWidget {
  const LegalScreen({super.key, required this.kind});

  final String kind;

  @override
  Widget build(BuildContext context) {
    final (title, body) = switch (kind) {
      'terms' => (S.t('profile.terms'), _terms),
      _ => (S.t('profile.privacy'), _privacy),
    };
    return Scaffold(
      appBar: AppBar(leading: const BackButton(), title: Text(title)),
      body: ListView(
        padding: const EdgeInsets.all(AppSpacing.lg),
        children: [Text(body, style: AppTypography.bodySecondary)],
      ),
    );
  }
}

const _privacy = '''
KORA — платформа доставки по Казахстану. Мы собираем минимум данных, необходимых для работы сервиса.

ЧТО МЫ СОБИРАЕМ
• Телефон (+7…) — для регистрации и входа по SMS-коду.
• Имя — показывается магазинам и курьерам при заказе.
• Адреса и точки доставки — для доставки заказов. Точка доставки сохраняется в заказе на момент оформления и не изменяется задним числом.
• Геопозиция — только при выборе точки доставки. Точное местоположение курьера видно клиенту только во время активной доставки.
• Заказы и статус оплаты — для исполнения заказа и возвратов. Платёжные данные обрабатывает платёжный провайдер (Kaspi), мы не храним данные карт.
• Чат по заказу — переписка между клиентом, магазином и курьером внутри заказа.
• Токен устройства — для push-уведомлений о статусе заказа.

КАМЕРА, МИКРОФОН, ГАЛЕРЕЯ
Запрашиваются только в момент использования: фото для чата, голосовые сообщения и звонки. Биометрическая аутентификация выполняется локально на устройстве, биометрические данные не передаются.

ХРАНЕНИЕ И УДАЛЕНИЕ
Аккаунт можно удалить прямо в приложении: Профиль → Удалить аккаунт. Данные, которые мы обязаны хранить по законодательству РК (финансовые и операционные записи), обезличиваются и хранятся ограниченный срок.

ПЕРЕДАЧА ДАННЫХ
Мы не продаём персональные данные. Доступ ограничен по ролям: магазин видит данные своих заказов, курьер — активных доставок, администратор действует по регламенту с записью в журнале аудита.

Контакты: support@kora.kz
''';

const _terms = '''
